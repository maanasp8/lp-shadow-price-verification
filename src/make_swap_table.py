"""Emit the generator swap-taxonomy table. 2026-09-07.

Follows the convention of make_results_tables.py: the caption lives here, not in
the .tex, and every cell is asserted against the persisted artefact.

THE DENOMINATOR POOLS TWO GENERATION RUNS. They are separate runs because what
the prompt discloses changes what the generator writes, so the caption says so.
Quoting 9/28 without that is the denominator error this project has made before.

    venv/bin/python src/make_swap_table.py
"""
from __future__ import annotations
import json, os, sys
from math import sqrt

OUT = os.environ.get("SWAP_TABLE_OUT", "tables_swap.tex")
RUNS = [("no row names", "data/prevalence_generated_haiku_plain_2026-09-03.json"),
        ("row names supplied", "data/prevalence_generated_haiku_rowlabels_2026-09-03.json")]
SWAP_KINDS = ["swap_within_row", "swap_cross_row", "swap_objective", "swap_limit"]
LABEL = {"swap_within_row": "within a row", "swap_cross_row": "across rows",
         "swap_objective": "in the objective", "swap_limit": "in a limit"}


def wilson(x, n, z=1.959963985):
    ph = x / n
    den = 1 + z * z / n
    c = (ph + z * z / (2 * n)) / den
    half = z * sqrt(ph * (1 - ph) / n + z * z / (4 * n * n)) / den
    return 100 * (c - half), 100 * (c + half)


def main():
    kinds, dev, swaps, scored = {}, 0, 0, 0
    for _lab, path in RUNS:
        if not os.path.exists(path):
            sys.exit(f"missing artefact {path}; run src/prevalence_generated.py")
        d = json.load(open(path))
        dev += d["deviating_models"]
        swaps += d["models_with_value_swap"]
        scored += d["scored"]
        for k, v in d["error_kind_counts"].items():
            kinds[k] = kinds.get(k, 0) + v

    # the claims the body makes, asserted so body and table cannot drift
    n_swap = sum(kinds.get(k, 0) for k in SWAP_KINDS)
    assert n_swap == swaps, f"swap kinds {n_swap} != models with a swap {swaps}"
    assert all(kinds.get(k, 0) > 0 for k in SWAP_KINDS), \
        f"not all four swap types observed: {[(k, kinds.get(k, 0)) for k in SWAP_KINDS]}"
    lo, hi = wilson(swaps, dev)
    pct = 100.0 * swaps / dev

    rows = "\n".join(
        f"    a value swap {LABEL[k]} & {kinds[k]} \\\\" for k in SWAP_KINDS)
    other = sorted((k, v) for k, v in kinds.items() if k not in SWAP_KINDS)
    rows += "\n    \\midrule\n" + "\n".join(
        f"    {k.replace('_', ' ')} & {v} \\\\" for k, v in other)

    caption = (
        f"Error kinds in the {dev} generated models that deviate from the "
        f"annotation. \\textsc{{claude-haiku-4.5}} was given each problem's text "
        f"and its variable names and asked for a linear program. "
        f"\\textbf{{{swaps} of the {dev}, {pct:.1f}\\% with a Wilson $95\\%$ "
        f"interval of $[{lo:.1f}, {hi:.1f}]$, contain a value swap}}, and the "
        f"four swap rows are the four types that produce the certified class, "
        f"all of them observed. A model may carry more than one kind, so the "
        f"column sums past {dev}. "
        f"\\textbf{{The denominator pools two generation runs}}, one prompted "
        f"without the annotation's row names and one with them, over {scored} "
        f"scored generations. They are separate runs because what the prompt "
        f"discloses changes what the generator writes, so this is a statement "
        f"about the generator rather than about either prompt. It is an "
        f"existence result and not a prevalence estimate: see "
        f"\\S\\ref{{sec:generated}} for why this corpus is roughly twenty times "
        f"too small to support one.")

    tex = f"""% GENERATED by src/make_swap_table.py. Do not edit by hand.
% Every cell is asserted against data/prevalence_generated_haiku_*.json, including
% that all four producing swap types are observed and that the swap-kind counts
% agree with the per-model swap count.
\\begin{{table}}[t]
  \\caption{{{caption}}}
  \\label{{tab:swaptaxonomy}}
  \\centering
  \\footnotesize
  \\setlength{{\\tabcolsep}}{{6pt}}
  \\begin{{tabular}}{{@{{}}lr@{{}}}}
    \\toprule
    error kind & models \\\\
    \\midrule
{rows}
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
"""
    d = os.path.dirname(OUT)
    if d:
        os.makedirs(d, exist_ok=True)
    open(OUT, "w").write(tex)
    print(f"wrote {OUT}")
    print(f"  {swaps}/{dev} = {pct:.1f}% [{lo:.1f}, {hi:.1f}]  over {scored} generations")
    for k in SWAP_KINDS:
        print(f"    {k:18s} {kinds[k]}")


if __name__ == "__main__":
    main()
